/**
 * Resolve an icon value (icon-ID string, emoji character, or legacy key) into
 * SVG path data. Returns `undefined` when no match is found.
 */
export function getIconPaths(value: string | undefined | null): string[] | undefined {
  if (value === undefined || value === null || value === '') return undefined;

  // Direct icon-ID match
  const direct = ICON_MAP.get(value);
  if (direct !== undefined) return direct.paths;

  // Legacy emoji character → icon-ID
  const mapped = EMOJI_TO_ICON[value];
  if (mapped !== undefined) return ICON_MAP.get(mapped)?.paths;

  return undefined;
}

/** Get the full icon def for metadata (label, category). */
export function getIconDef(value: string | undefined | null): AgentIconDef | undefined {
  if (value === undefined || value === null || value === '') return undefined;
  return ICON_MAP.get(value) ?? ICON_MAP.get(EMOJI_TO_ICON[value] ?? '');
}

