/** Generate a checkered floor tile pattern (16x16) */
export function checkerFloor(color1: string, color2: string): string[][] {
  const tile: string[][] = [];
  for (let y = 0; y < 16; y++) {
    const row: string[] = [];
    for (let x = 0; x < 16; x++) {
      const isAlt = (Math.floor(x / 8) + Math.floor(y / 8)) % 2 === 0;
      row.push(isAlt ? color1 : color2);
    }
    tile.push(row);
  }
  return tile;
}

/** Grid-line floor (graph paper feel) for Engineering */
export function gridFloor(baseColor: string, lineColor: string): string[][] {
  const tile: string[][] = [];
  for (let y = 0; y < 16; y++) {
    const row: string[] = [];
    for (let x = 0; x < 16; x++) {
      const isLine = x === 0 || x === 8 || y === 0 || y === 8;
      row.push(isLine ? lineColor : baseColor);
    }
    tile.push(row);
  }
  return tile;
}

/** Herringbone / diagonal floor for Operations */
export function herringboneFloor(color1: string, color2: string): string[][] {
  const tile: string[][] = [];
  for (let y = 0; y < 16; y++) {
    const row: string[] = [];
    for (let x = 0; x < 16; x++) {
      const stripe = Math.floor((x + y) / 4) % 2 === 0;
      row.push(stripe ? color1 : color2);
    }
    tile.push(row);
  }
  return tile;
}

/** Dot grid floor for Research */
